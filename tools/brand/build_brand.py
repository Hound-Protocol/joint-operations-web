#!/usr/bin/env python3
"""Build the Hound Protocol and Joint Operations brand marks as SVG files.

All artwork is original vector geometry drawn in code. Wordmarks use Barlow
Semi Condensed (SIL Open Font License), converted to outlines so the files look
the same everywhere. See docs/brand.md for usage rules.

Usage: python3 tools/brand/build_brand.py   (writes site/assets/brand/*.svg and site/assets/img/favicon.svg)
"""
import math, pathlib, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import logos  # noqa: E402
import salute  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "site/assets/brand"
FONTS = ROOT / "site/assets/fonts"
WHITE, AMBER, INK = "#e9edee", "#c9a24a", "#0b0e10"
# Brand colours: Joint Operations is orange and white, Hound Protocol is white, black and red
ORANGE, RED, PAPER = "#f28c28", "#d0303a", "#f3efe6"



def text_path(text, font="barlow-semi-condensed-light.woff", size=40, tracking=0.3, x=0, y=0, anchor="start"):
    """Outline text as one SVG path. tracking is extra space per letter, as a share of the font size."""
    f = TTFont(FONTS / font)
    cmap, gs, upm = f.getBestCmap(), f.getGlyphSet(), f["head"].unitsPerEm
    scale, adv = size / upm, []
    for ch in text:
        g = cmap.get(ord(ch))
        adv.append((g, gs[g].width * scale if g else size * 0.3))
    width = sum(a for _, a in adv) + tracking * size * (len(text) - 1)
    cx = x - (width if anchor == "end" else width / 2 if anchor == "middle" else 0)
    d = []
    for g, a in adv:
        if g:
            pen = SVGPathPen(gs)
            gs[g].draw(TransformPen(pen, (scale, 0, 0, -scale, cx, y)))
            d.append(pen.getCommands())
        cx += a + tracking * size
    return " ".join(d), width










def svg(w, h, body, title):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-label="{title}"><title>{title}</title>{body}</svg>\n'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    tp = text_path
    hp, hp_lock = logos.hp_icon(), logos.hp_lockup(tp)
    jo_b, jo_w = logos.jo_badge(tp), logos.jo_wordmark(tp)
    files = {
        # Hound Protocol: the hound over the red slash. Mark alone, and with the name (lockup)
        "hound-protocol-mark.svg": svg(200, 200, hp, "Hound Protocol"),
        "hound-protocol-mark-mono.svg": svg(200, 200, logos.mono(hp, 200, 200, "hp-m"), "Hound Protocol"),
        "hound-protocol-mark-light.svg": svg(200, 200, logos.hp_icon(fg=INK, cut=PAPER), "Hound Protocol"),
        "hound-protocol-lockup.svg": svg(260, 240, hp_lock, "Hound Protocol"),
        "hound-protocol-lockup-mono.svg": svg(260, 240, logos.mono(hp_lock, 260, 240, "hp-lm"), "Hound Protocol"),
        "hound-protocol-lockup-light.svg": svg(260, 240, logos.hp_lockup(tp, fg=INK, cut=PAPER), "Hound Protocol"),
        # Joint Operations: the unit badge is the mark, the wordmark is the lockup
        "joint-operations-mark.svg": svg(260, 240, jo_b, "Joint Operations"),
        "joint-operations-mark-mono.svg": svg(260, 240, logos.mono(jo_b, 260, 240, "jo-m"), "Joint Operations"),
        "joint-operations-mark-light.svg": svg(260, 240, logos.jo_badge(tp, frame=INK, field=PAPER, band_text=PAPER, star=INK), "Joint Operations"),
        "joint-operations-lockup.svg": svg(260, 240, jo_w, "Joint Operations"),
        "joint-operations-lockup-mono.svg": svg(260, 240, logos.mono(jo_w, 260, 240, "jo-lm"), "Joint Operations"),
        "joint-operations-lockup-light.svg": svg(260, 240, logos.jo_wordmark(tp, fg=INK, cut=PAPER), "Joint Operations"),
    }
    # White one-colour badge for dark page backgrounds (an <img> cannot inherit currentColor)
    files["joint-operations-mark-white.svg"] = files["joint-operations-mark-mono.svg"].replace("currentColor", WHITE)
    # Background scene for the website: saluting operatives and their commander, one colour
    files["joint-operations-salute.svg"] = salute.scene(WHITE)
    for name, body in files.items():
        (OUT / name).write_text(body, encoding="utf-8")
    # Favicon: the badge simplified for 16 to 64 px (shield, star, host diamond; no lettering)
    fav = (logos._poly([(18, 14), (182, 14), (182, 124), (100, 188), (18, 124)], WHITE) +
           logos._poly([(32, 28), (168, 28), (168, 117), (100, 170), (32, 117)], INK) +
           logos.star16(100, 92, 62, 18, WHITE) + logos._poly([(100, 70), (122, 92), (100, 114), (78, 92)], ORANGE))
    (ROOT / "site/assets/img/favicon.svg").write_text(svg(200, 200, fav, "Joint Operations"), encoding="utf-8")
    # Inline marks for the site script (one colour, follows the text colour)
    js = ("  /* Brand marks, generated by tools/brand/build_brand.py. Do not edit by hand. */\n"
          "  var BRAND = {\n"
          f"    hpColor: '<svg class=\"bm\" viewBox=\"0 0 200 200\" aria-hidden=\"true\">{hp}</svg>',\n"
          f"    joColor: '<svg class=\"bm\" viewBox=\"0 0 260 240\" aria-hidden=\"true\">{jo_b}</svg>'\n"
          "  };\n")
    (ROOT / "site/src/js/04b-brand.js").write_text(js, encoding="utf-8")
    print("Wrote", ", ".join(files), "+ favicon.svg, site/src/js/04b-brand.js")


if __name__ == "__main__":
    main()
